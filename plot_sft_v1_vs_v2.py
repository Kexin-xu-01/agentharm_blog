#!/usr/bin/env python3
"""AgentHarm SFT v1 vs v2: category coverage, topic diversity, the word "fake", length,
lexical and semantic diversity, and a joint UMAP of the user prompts.

Data (hedgehog-quills/benchmarks/agentharm/datasets/sft-toolcalling/combined/):
  v1/agentharm_sft_toolcalling.jsonl     2,531 rows, 4 generator models, 5 categories
  v2.1/agentharm_sft_toolcalling_v2.1.jsonl
                                         1,702 rows = v2 (1,350) plus the two benign publictest
                                         gap-fill batches; Claude Sonnet 5 only, no benign_general
Note v2 is generated by Claude Sonnet 5 only, while v1 mixes four generator models.
Figures label v2.1 as "v2"; --v2 can point at combined/v2 to leave the gap-fill rows out.

Figures (each .pdf + .png):
  sft_v1_vs_v2_coverage   (a) rows, (b) distinct topic-graph nodes (metadata.topic_id) and
                          (c) % of user prompts containing a word starting with "fake",
                          per category.
  sft_v1_vs_v2_summary    (a) rows and (b) % of prompts containing "fake" (as coverage a, c);
                          (c) prompt and (d) response length (whitespace words);
                          (e) prompt lexical diversity: distinct bigrams / all bigrams in
                          random 3,000-word samples of each category's prompts (a fixed
                          word budget, because v2 prompts are twice as long and type-token
                          ratios fall with length; mean and s.d. over 50 samples);
                          (f) prompt semantic diversity: per prompt, the mean cosine distance
                          to every other prompt of the same category in the same version.
  sft_v1_vs_v2_umap       one UMAP fitted on v1 + v2.1 prompts together (all-mpnet-base-v2,
                          cosine, n_neighbors=30, min_dist=0.15, seed 42); (a) v1 and (b) v2
                          coloured by category, with the other dataset in grey behind.
Embeddings and the joint UMAP come from sky_embed/embed_v2.sky.yaml (a SkyPilot job).

Usage (from /home/jovyan/Shared/kexin):
    python agentharm_blog/plot_sft_v1_vs_v2.py --out-dir agentharm_blog/figures
"""

import argparse
import json
import random
import re
from collections import Counter
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.lines import Line2D
from matplotlib.patches import Patch

import style
from style import CATEGORIES, TOL, WIDTH

DATA = Path("/home/jovyan/Shared/kexin/hedgehog-quills/benchmarks/agentharm/datasets/"
            "sft-toolcalling/combined")
EMB = Path("/home/jovyan/Shared/kexin/agentharm_blog/sky_embed")
GROUPS = [  # key, label, colour
    ("v1", "v1", TOL["cyan"]),
    ("v2", "v2", TOL["indigo"]),
]
CAT_TICKS = ["Cyber harmful", "Cyber benign", "Fraud harmful", "Fraud benign", "General benign"]
FAKE_RE = re.compile(r"\bfake", re.I)
WORD_RE = re.compile(r"[A-Za-z][A-Za-z'-]*")
BOX = dict(patch_artist=True, medianprops=dict(color="black", lw=0.8),
           whiskerprops=dict(lw=0.6), capprops=dict(lw=0.6), boxprops=dict(lw=0.6),
           flierprops=dict(marker=".", ms=1.5, mfc="#888888", mec="none"))


def load(path):
    rows = []
    for line in path.open():
        r = json.loads(line)
        msg = {m["role"]: m.get("content") or "" for m in r["messages"]}
        md = r["metadata"]
        rows.append(dict(cat=md["attack_type"], model=md["generator_model"], topic=md["topic_id"],
                         user=msg["user"], assistant=msg["assistant"]))
    return rows


def distinct2(texts, budget=3000, reps=50, seed=0):
    """Distinct bigrams / bigrams in random samples of whole prompts totalling `budget` words."""
    toks = [[w.lower() for w in WORD_RE.findall(t)] for t in texts]
    rng = random.Random(seed)
    out = []
    for _ in range(reps):
        grams = []
        for i in rng.sample(range(len(toks)), len(toks)):
            grams += zip(toks[i], toks[i][1:])
            if len(grams) >= budget:
                break
        out.append(len(set(grams)) / len(grams))
    return np.mean(out), np.std(out)


def semantic_diversity(E):
    n = len(E)
    return 1 - ((E @ E.T).sum(1) - 1) / (n - 1)


def grouped_bars(ax, getter, width=0.36):
    for g, (gk, gl, gc) in enumerate(GROUPS):
        x = np.arange(len(CATEGORIES)) + (g - 0.5) * width
        ax.bar(x, [getter(gk, c) for c, _, _ in CATEGORIES], width, color=gc, label=gl)
    ax.set_xticks(range(len(CATEGORIES)), CAT_TICKS, rotation=30, ha="right", rotation_mode="anchor")
    ax.tick_params(axis="x", length=0, labelsize=6)


def grouped_boxes(ax, getter, width=0.36):
    for g, (gk, gl, gc) in enumerate(GROUPS):
        for i, (c, _, _) in enumerate(CATEGORIES):
            v = getter(gk, c)
            if len(v) < 2:
                continue
            b = ax.boxplot(v, positions=[i + (g - 0.5) * width], widths=width * 0.85, **BOX)
            b["boxes"][0].set_facecolor(gc)
    ax.set_xticks(range(len(CATEGORIES)), CAT_TICKS, rotation=30, ha="right", rotation_mode="anchor")
    ax.set_xlim(-0.5, len(CATEGORIES) - 0.5)
    ax.tick_params(axis="x", length=0, labelsize=6)


def legend_below(fig, y=-0.01):
    fig.legend([Patch(fc=c) for _, _, c in GROUPS],
               [l for _, l, _ in GROUPS], loc="lower center", bbox_to_anchor=(0.5, y), ncol=2)


def fig_coverage(G):
    fig, axes = plt.subplots(1, 3, figsize=(WIDTH, 2.2))
    sel = lambda g, c: [r for r in G[g] if r["cat"] == c]  # noqa: E731
    grouped_bars(axes[0], lambda g, c: len(sel(g, c)))
    axes[0].set_ylabel("Rows")
    axes[0].set_title("(a) Rows")
    grouped_bars(axes[1], lambda g, c: len({r["topic"] for r in sel(g, c)}))
    axes[1].set_ylabel("Distinct topics")
    axes[1].set_title("(b) Topic-graph nodes used")
    grouped_bars(axes[2], lambda g, c: 100 * np.mean([bool(FAKE_RE.search(r["user"])) for r in sel(g, c)])
                 if sel(g, c) else 0)
    axes[2].set_ylabel("Prompts (%)")
    axes[2].set_title('(c) Prompts containing "fake"')
    legend_below(fig)
    fig.tight_layout(rect=(0, 0.07, 1, 1), w_pad=1.2)
    return fig


def fig_summary(G, E):
    fig = plt.figure(figsize=(WIDTH, 6.3))
    gs = fig.add_gridspec(3, 2, hspace=0.62, wspace=0.28)
    sel = lambda g, c, k: np.array([r[k] for r in G[g] if r["cat"] == c], float)  # noqa: E731
    rows = lambda g, c: [r for r in G[g] if r["cat"] == c]  # noqa: E731
    ax = fig.add_subplot(gs[0, 0])
    grouped_bars(ax, lambda g, c: len(rows(g, c)), width=0.36)
    ax.set_ylabel("Rows")
    ax.set_title("(a) Rows")
    ax = fig.add_subplot(gs[0, 1])
    grouped_bars(ax, lambda g, c: 100 * np.mean([bool(FAKE_RE.search(r["user"])) for r in rows(g, c)])
                 if rows(g, c) else 0, width=0.36)
    ax.set_ylabel("Prompts (%)")
    ax.set_title('(b) Prompts containing "fake"')

    for col, (key, title, ticks) in enumerate([("user_words", "(c) Prompt length", [5, 10, 20, 50, 100]),
                                               ("asst_words", "(d) Response length", [10, 100, 1000])]):
        ax = fig.add_subplot(gs[1, col])
        grouped_boxes(ax, lambda g, c: sel(g, c, key))
        ax.set_yscale("log")
        ax.set_yticks(ticks, [str(t) for t in ticks])
        ax.yaxis.set_minor_formatter(mpl.ticker.NullFormatter())
        ax.set_ylabel("Words")
        ax.set_title(title)

    ax = fig.add_subplot(gs[2, 0])
    width = 0.36
    for g, (gk, gl, gc) in enumerate(GROUPS):
        for i, (c, _, _) in enumerate(CATEGORIES):
            texts = [r["user"] for r in G[gk] if r["cat"] == c]
            if not texts:
                continue
            m, s = distinct2(texts)
            ax.bar(i + (g - 0.5) * width, m, width, yerr=s, color=gc, error_kw=dict(lw=0.6))
    ax.set_xticks(range(len(CATEGORIES)), CAT_TICKS, rotation=30, ha="right", rotation_mode="anchor")
    ax.tick_params(axis="x", length=0, labelsize=6)
    ax.set_ylim(0.35, None)
    ax.set_ylabel("Distinct bigrams")
    ax.set_title("(e) Prompt lexical diversity")

    for gk in E:
        for c, _, _ in CATEGORIES:
            idx = [i for i, r in enumerate(G[gk]) if r["cat"] == c]
            if len(idx) > 1:
                for i, v in zip(idx, semantic_diversity(E[gk][idx])):
                    G[gk][i]["sem_div"] = float(v)
    ax = fig.add_subplot(gs[2, 1])
    grouped_boxes(ax, lambda g, c: sel(g, c, "sem_div"))
    ax.set_ylabel("Mean cosine distance")
    ax.set_title("(f) Prompt semantic diversity")
    legend_below(fig, y=-0.005)
    fig.subplots_adjust(bottom=0.115, top=0.97)
    return fig


def fig_umap(G, Y, seed):
    fig, axes = plt.subplots(1, 2, figsize=(WIDTH, 2.9), sharex=True, sharey=True)
    color = {k: c for k, _, c in CATEGORIES}
    rng = np.random.default_rng(seed)
    for ax, (fg, bg, title) in zip(axes, [("v1", "v2", "(a) v1"), ("v2", "v1", "(b) v2")]):
        ax.scatter(Y[bg][:, 0], Y[bg][:, 1], s=3, lw=0, c="#E4E4E4", rasterized=True)
        order = rng.permutation(len(G[fg]))
        ax.scatter(Y[fg][order, 0], Y[fg][order, 1], s=3.5, lw=0,
                   c=[color[G[fg][i]["cat"]] for i in order], rasterized=True)
        ax.set_xticks([])
        ax.set_yticks([])
        ax.set_xlabel("UMAP-1")
        ax.set_ylabel("UMAP-2" if fg == "v1" else "")
        ax.set_title(f"{title} ({len(G[fg]):,} prompts)")
    fig.legend([Line2D([], [], ls="", marker="o", ms=3, mfc=c, mec="none") for _, _, c in CATEGORIES]
               + [Line2D([], [], ls="", marker="o", ms=3, mfc="#D0D0D0", mec="none")],
               [l for _, l, _ in CATEGORIES] + ["Other version"],
               loc="lower center", bbox_to_anchor=(0.5, -0.01), ncol=6, columnspacing=0.8, handletextpad=0.2)
    fig.tight_layout(rect=(0, 0.06, 1, 1), w_pad=1.0)
    return fig


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--v1", type=Path, default=DATA / "v1/agentharm_sft_toolcalling.jsonl")
    p.add_argument("--v2", type=Path, default=DATA / "v2.1/agentharm_sft_toolcalling_v2.1.jsonl")
    p.add_argument("--out-dir", type=Path, default=Path("agentharm_blog/figures"))
    p.add_argument("--dpi", type=int, default=600, help="PNG resolution (PDFs are vector)")
    p.add_argument("--seed", type=int, default=42)
    figs = ["coverage", "summary", "umap"]
    p.add_argument("--only", choices=figs, nargs="+", default=figs)
    a = p.parse_args()

    style.use()
    v1, v2 = load(a.v1), load(a.v2)
    for r in v1 + v2:
        r["user_words"] = len(r["user"].split())
        r["asst_words"] = len(r["assistant"].split())
    G = {"v1": v1, "v2": v2}
    print({k: len(v) for k, v in G.items()})
    out = lambda stem: str(a.out_dir / stem)  # noqa: E731

    if "coverage" in a.only:
        style.save(fig_coverage(G), out("sft_v1_vs_v2_coverage"), a.dpi)
    if a.only == ["coverage"]:
        return
    # v1 embeddings are in dataset order; v2.1 embeddings are matched to --v2 by prompt text
    X1 = np.load(EMB / "emb_all-mpnet-base-v2.npy")
    X21 = np.load(EMB / "emb_all-mpnet-base-v2_v2.1.npy")
    texts21 = [json.loads(l) for l in open(EMB / "texts_v2.1.jsonl")]
    pos = {t: i for i, t in enumerate(texts21)}
    idx2 = np.array([pos[r["user"]] for r in v2])
    if "summary" in a.only:
        style.save(fig_summary(G, {"v1": X1, "v2": X21[idx2]}), out("sft_v1_vs_v2_summary"), a.dpi)
    if "umap" in a.only:
        Y = np.load(EMB / f"umap_semantic_v1_v2.1_s{a.seed}.npy")
        Y = {"v1": Y[:len(v1)], "v2": Y[len(v1):][idx2]}
        style.save(fig_umap(G, Y, a.seed), out("sft_v1_vs_v2_umap"), a.dpi)


if __name__ == "__main__":
    main()
